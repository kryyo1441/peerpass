// Package signaling holds the room/peer model that lets PeerPass clients find
// each other before a direct WebRTC connection exists. It has no networking
// code of its own -- see internal/signalserver for the transport that drives
// this package over WebSockets.
package signaling

import (
	"crypto/rand"
	"encoding/json"
	"errors"
	"sync"
)

// MaxPeersPerRoom bounds room size. Arbitrary for now (host + a handful of
// viewers); revisit once Phase D (multi-viewer video) picks a real topology
// and room-size limit.
const MaxPeersPerRoom = 8

var (
	ErrRoomNotFound     = errors.New("signaling: room not found")
	ErrRoomFull         = errors.New("signaling: room is full")
	ErrPeerNotInRoom    = errors.New("signaling: peer not in room")
	ErrRecipientUnknown = errors.New("signaling: recipient not in room")
)

// PeerID identifies one connected peer within a room. Assigned by the
// server -- never trust a peer ID supplied by a client.
type PeerID string

// RoomCode identifies a room. Generated by the server at creation time.
type RoomCode string

// Message types exchanged over the wire, after the initial room
// creation/join handshake.
const (
	TypeWelcome    = "welcome"     // server -> joining peer: room code, peer id, current peer list
	TypePeerJoined = "peer-joined" // server -> existing peers: someone joined
	TypePeerLeft   = "peer-left"   // server -> remaining peers: someone left
	TypeRoomClosed = "room-closed" // server -> remaining peers: host left, room is gone
	TypeRelay      = "relay"       // client -> server -> recipient: opaque payload (SDP, ICE, etc. from M4 on)
	TypeError      = "error"       // server -> peer: something went wrong
)

// Envelope is the message shape exchanged over the signaling connection.
// Payload is intentionally opaque (json.RawMessage) -- the signaling layer
// never needs to understand WebRTC SDP/ICE content, it just relays it.
type Envelope struct {
	Type    string          `json:"type"`
	From    PeerID          `json:"from,omitempty"`
	To      PeerID          `json:"to,omitempty"`
	Payload json.RawMessage `json:"payload,omitempty"`
}

// Peer is one connected client. Send is the outbound queue the transport
// layer (internal/signalserver) drains and writes to the actual socket --
// the Hub never does I/O itself.
type Peer struct {
	ID   PeerID
	Send chan Envelope
}

// Room is a single N-party session: one host (the creator) plus any number
// of other peers, up to MaxPeersPerRoom.
type Room struct {
	Code  RoomCode
	Host  PeerID
	Peers map[PeerID]*Peer
}

// PeerIDs returns the room's current peer IDs. Caller must hold the Hub's
// lock (only called from within Hub methods).
func (r *Room) peerIDs() []PeerID {
	ids := make([]PeerID, 0, len(r.Peers))
	for id := range r.Peers {
		ids = append(ids, id)
	}
	return ids
}

// Hub owns every active room and is safe for concurrent use. One Hub serves
// the whole signaling process; each connection handler calls into it.
type Hub struct {
	mu    sync.Mutex
	rooms map[RoomCode]*Room
}

func NewHub() *Hub {
	return &Hub{rooms: make(map[RoomCode]*Room)}
}

// CreateRoom makes a new room, registers its creator as the host, and
// returns the room code and the host's assigned peer ID.
func (h *Hub) CreateRoom() (RoomCode, PeerID, *Peer) {
	h.mu.Lock()
	defer h.mu.Unlock()

	code := h.newRoomCode()
	hostID := newPeerID()
	peer := &Peer{ID: hostID, Send: make(chan Envelope, 16)}

	h.rooms[code] = &Room{
		Code:  code,
		Host:  hostID,
		Peers: map[PeerID]*Peer{hostID: peer},
	}
	return code, hostID, peer
}

// JoinRoom adds a new peer to an existing room, broadcasts the join to
// existing peers, and returns the new peer's ID plus the full peer list
// (including itself) for the welcome message.
func (h *Hub) JoinRoom(code RoomCode) (PeerID, *Peer, []PeerID, error) {
	h.mu.Lock()
	defer h.mu.Unlock()

	room, ok := h.rooms[code]
	if !ok {
		return "", nil, nil, ErrRoomNotFound
	}
	if len(room.Peers) >= MaxPeersPerRoom {
		return "", nil, nil, ErrRoomFull
	}

	id := newPeerID()
	peer := &Peer{ID: id, Send: make(chan Envelope, 16)}
	room.Peers[id] = peer

	h.broadcast(room, Envelope{Type: TypePeerJoined, From: id}, id)

	return id, peer, room.peerIDs(), nil
}

// Leave removes a peer from its room. If the departing peer was the host,
// the room closes and every remaining peer is notified with TypeRoomClosed;
// otherwise the remaining peers get a TypePeerLeft. This is the simplest
// rule that fits the product: the host is the game machine, so no host
// means there's nothing left to connect to.
func (h *Hub) Leave(code RoomCode, id PeerID) error {
	h.mu.Lock()
	defer h.mu.Unlock()

	room, ok := h.rooms[code]
	if !ok {
		return ErrRoomNotFound
	}
	if _, ok := room.Peers[id]; !ok {
		return ErrPeerNotInRoom
	}

	if id == room.Host {
		for peerID, peer := range room.Peers {
			if peerID != id {
				h.send(peer, Envelope{Type: TypeRoomClosed})
			}
		}
		delete(h.rooms, code)
		return nil
	}

	delete(room.Peers, id)
	h.broadcast(room, Envelope{Type: TypePeerLeft, From: id}, "")
	return nil
}

// Relay forwards payload from one peer to another within the same room.
// The server stamps From itself; a client-supplied From is never trusted.
func (h *Hub) Relay(code RoomCode, from, to PeerID, payload json.RawMessage) error {
	h.mu.Lock()
	defer h.mu.Unlock()

	room, ok := h.rooms[code]
	if !ok {
		return ErrRoomNotFound
	}
	if _, ok := room.Peers[from]; !ok {
		return ErrPeerNotInRoom
	}
	recipient, ok := room.Peers[to]
	if !ok {
		return ErrRecipientUnknown
	}

	h.send(recipient, Envelope{Type: TypeRelay, From: from, To: to, Payload: payload})
	return nil
}

// broadcast sends env to every peer in room except skip (use "" to skip none).
func (h *Hub) broadcast(room *Room, env Envelope, skip PeerID) {
	for id, peer := range room.Peers {
		if id == skip {
			continue
		}
		h.send(peer, env)
	}
}

// send is non-blocking: a slow/dead peer's full buffer must never stall the
// hub for everyone else. The transport layer is responsible for noticing a
// peer stopped draining its channel and disconnecting it.
func (h *Hub) send(peer *Peer, env Envelope) {
	select {
	case peer.Send <- env:
	default:
	}
}

const roomCodeAlphabet = "ABCDEFGHJKLMNPQRSTUVWXYZ23456789" // no 0/O/1/I, easier to read aloud
const roomCodeLength = 6

// newRoomCode generates a room code and retries on the astronomically
// unlikely collision with an existing room. Caller must hold h.mu.
func (h *Hub) newRoomCode() RoomCode {
	for {
		code := RoomCode(randomString(roomCodeAlphabet, roomCodeLength))
		if _, exists := h.rooms[code]; !exists {
			return code
		}
	}
}

func newPeerID() PeerID {
	const alphabet = "abcdefghijklmnopqrstuvwxyz0123456789"
	return PeerID(randomString(alphabet, 12))
}

func randomString(alphabet string, n int) string {
	b := make([]byte, n)
	idx := make([]byte, n)
	if _, err := rand.Read(idx); err != nil {
		panic("signaling: crypto/rand failed: " + err.Error())
	}
	for i, v := range idx {
		b[i] = alphabet[int(v)%len(alphabet)]
	}
	return string(b)
}
